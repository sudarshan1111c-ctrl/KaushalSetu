"""Database models for KaushalSetu.

We use Flask‑SQLAlchemy. The four main user types are represented via a
single `User` model with a `role` column. Associated profile tables store
role‑specific information.
"""

from . import db
from flask_login import UserMixin
from werkzeug.security import generate_password_hash, check_password_hash
from datetime import datetime

class User(db.Model, UserMixin):
    __tablename__ = "users"
    id = db.Column(db.Integer, primary_key=True)
    email = db.Column(db.String(120), unique=True, nullable=False)
    password_hash = db.Column(db.String(128), nullable=False)
    # role: 'shg', 'youth', 'employer', 'admin'
    role = db.Column(db.String(20), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # relationships
    shg_profile = db.relationship("SHGProfile", uselist=False, back_populates="user")
    youth_profile = db.relationship("YouthProfile", uselist=False, back_populates="user")
    employer_profile = db.relationship("EmployerProfile", uselist=False, back_populates="user")

    def set_password(self, password: str) -> None:
        self.password_hash = generate_password_hash(password)

    def check_password(self, password: str) -> bool:
        return check_password_hash(self.password_hash, password)

    def __repr__(self):
        return f"<User {self.email} ({self.role})>"

class SHGProfile(db.Model):
    __tablename__ = "shg_profiles"
    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(150), nullable=False)
    description = db.Column(db.Text)
    location = db.Column(db.String(100))
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    user = db.relationship("User", back_populates="shg_profile")
    # one‑to‑many: SHG can have many orders
    orders = db.relationship("Order", back_populates="shg", cascade="all, delete-orphan")

class YouthProfile(db.Model):
    __tablename__ = "youth_profiles"
    id = db.Column(db.Integer, primary_key=True)
    full_name = db.Column(db.String(150), nullable=False)
    skills = db.Column(db.String(250))  # comma‑separated skill list
    availability = db.Column(db.String(100))
    location = db.Column(db.String(100))
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    user = db.relationship("User", back_populates="youth_profile")
    applications = db.relationship("Application", back_populates="youth", cascade="all, delete-orphan")

class EmployerProfile(db.Model):
    __tablename__ = "employer_profiles"
    id = db.Column(db.Integer, primary_key=True)
    company_name = db.Column(db.String(150), nullable=False)
    contact_person = db.Column(db.String(150))
    location = db.Column(db.String(100))
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    user = db.relationship("User", back_populates="employer_profile")
    # employers can also post orders directly (similar to SHG)
    orders = db.relationship("Order", back_populates="employer", cascade="all, delete-orphan")

class Order(db.Model):
    __tablename__ = "orders"
    id = db.Column(db.Integer, primary_key=True)
    title = db.Column(db.String(200), nullable=False)
    description = db.Column(db.Text)
    quantity = db.Column(db.Integer, nullable=False)
    deadline = db.Column(db.DateTime, nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    # foreign keys – either shg_id or employer_id will be set (mutually exclusive)
    shg_id = db.Column(db.Integer, db.ForeignKey("shg_profiles.id"))
    employer_id = db.Column(db.Integer, db.ForeignKey("employer_profiles.id"))
    shg = db.relationship("SHGProfile", back_populates="orders")
    employer = db.relationship("EmployerProfile", back_populates="orders")
    # one order can generate many workforce requests
    workforce_requests = db.relationship("WorkforceRequest", back_populates="order", cascade="all, delete-orphan")

class WorkforceRequest(db.Model):
    """A request for additional workers generated by an Order.

    The rule‑based matcher will look for YouthProfile entries that match the
    required skills/availability/location.
    """
    __tablename__ = "workforce_requests"
    id = db.Column(db.Integer, primary_key=True)
    # New fields for detailed request information
    job_title = db.Column(db.String(200), nullable=False)
    required_skills = db.Column(db.String(250))  # comma‑separated
    needed_quantity = db.Column(db.Integer, nullable=False)
    location = db.Column(db.String(100))
    payment_amount = db.Column(db.Float)  # total payment offered
    duration_days = db.Column(db.Integer)  # expected work duration
    description = db.Column(db.Text)
    status = db.Column(db.String(20), default="open")  # open, fulfilled, closed
    order_id = db.Column(db.Integer, db.ForeignKey("orders.id"), nullable=False)
    order = db.relationship("Order", back_populates="workforce_requests")
    applications = db.relationship("Application", back_populates="request", cascade="all, delete-orphan")

class Application(db.Model):
    """Youth applies to a WorkforceRequest."""
    __tablename__ = "applications"
    id = db.Column(db.Integer, primary_key=True)
    request_id = db.Column(db.Integer, db.ForeignKey("workforce_requests.id"), nullable=False)
    youth_id = db.Column(db.Integer, db.ForeignKey("youth_profiles.id"), nullable=False)
    status = db.Column(db.String(20), default="pending")  # pending, accepted, rejected
    applied_at = db.Column(db.DateTime, default=datetime.utcnow)
    request = db.relationship("WorkforceRequest", back_populates="applications")
    youth = db.relationship("YouthProfile", back_populates="applications")

    __table_args__ = (db.UniqueConstraint('request_id', 'youth_id', name='_unique_application'),)
